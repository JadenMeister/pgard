// Regenerates src/standards/cert-java.ts from the SEI secure-coding-standards repository, pinned to
// one commit. Run manually (network access needed), then `npx prettier --write` the output:
//   node packages/findings/scripts/generate-cert-java.mjs > packages/findings/src/standards/cert-java.ts
// The test in src/standards/standards.test.ts pins the result with a hash. Only ids, titles, link
// paths and CWE ids are extracted.
const COMMIT = "72e8a329fb731831a21cbd8f480b85a2f2711ae5";
const RAW = `https://raw.githubusercontent.com/cmu-sei/secure-coding-standards/${COMMIT}/`;
const JAVA = "content/6.sei-cert-oracle-coding-standard-for-java/";
const CWE_PAGE = `${JAVA}5.back-matter/7.rule-or-rec-dd-related-guidelines/5.mitre-cwe.md`;

// Rules listed on the published Java rules index (the repository also holds retired ones).
const ALLOWED = new Set(
  `IDS00 IDS01 IDS03 IDS04 IDS06 IDS07 IDS08 IDS11 IDS14 IDS15 IDS16 IDS17 DCL00 DCL01 DCL02 EXP00 EXP01 EXP02 EXP03 EXP04 EXP05 EXP06 EXP07 NUM00 NUM01 NUM02 NUM03 NUM04 NUM07 NUM08 NUM09 NUM10 NUM11 NUM12 NUM13 NUM14 STR00 STR01 STR02 STR03 STR04 OBJ01 OBJ02 OBJ03 OBJ04 OBJ05 OBJ06 OBJ07 OBJ08 OBJ09 OBJ10 OBJ11 OBJ12 OBJ13 OBJ14 MET00 MET01 MET02 MET03 MET04 MET05 MET06 MET07 MET08 MET09 MET10 MET11 MET12 MET13 ERR00 ERR01 ERR02 ERR03 ERR04 ERR05 ERR06 ERR07 ERR08 ERR09 VNA00 VNA01 VNA02 VNA03 VNA04 VNA05 LCK00 LCK01 LCK02 LCK03 LCK04 LCK05 LCK06 LCK07 LCK08 LCK09 LCK10 LCK11 THI00 THI01 THI02 THI03 THI04 THI05 TPS00 TPS01 TPS02 TPS03 TPS04 TSM00 TSM01 TSM02 TSM03 FIO00 FIO01 FIO02 FIO03 FIO04 FIO05 FIO06 FIO07 FIO08 FIO09 FIO10 FIO11 FIO12 FIO13 FIO14 FIO15 FIO16 SER00 SER01 SER02 SER03 SER04 SER05 SER06 SER07 SER08 SER09 SER10 SER11 SER12 SEC00 SEC01 SEC02 SEC03 SEC04 SEC05 SEC06 SEC07 SEC08 SEC09 SEC10 ENV00 ENV01 ENV02 ENV03 ENV04 ENV05 ENV06 JNI00 JNI01 JNI02 JNI03 JNI04 MSC00 MSC01 MSC02 MSC03 MSC04 MSC05 MSC06 MSC07 MSC08 MSC09 MSC10 MSC11`
    .split(" ")
    .map((x) => `${x}-J`),
);
// Rules whose page has no "# ID. Title" heading in the repository; titles taken from the index.
const EXTRA = new Map([
  ["FIO04-J", ["Release resources when they are no longer needed", "input-output-fio/fio04-j"]],
  ["MSC02-J", ["Generate strong random numbers", "miscellaneous-msc/msc02-j"]],
  [
    "ENV03-J",
    ["Do not grant dangerous combinations of permissions", "runtime-environment-env/env03-j"],
  ],
]);

const get = async (url) => {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response.text();
};

const tree = await (
  await fetch(
    `https://api.github.com/repos/cmu-sei/secure-coding-standards/git/trees/${COMMIT}?recursive=1`,
  )
).json();
const files = tree.tree
  .map((entry) => entry.path)
  .filter(
    (path) => path.startsWith(`${JAVA}3.rules/`) && /\/[0-9]+\.[a-z]+[0-9]+-j\.md$/.test(path),
  );

const rules = [];
for (const [id, [title, path]] of EXTRA) rules.push({ id, title, path });
let next = 0;
async function worker() {
  while (next < files.length) {
    const file = files[next++];
    if (/env03-j|fio04-j|msc02-j/.test(file)) continue;
    const head = (await get(RAW + file.split("/").map(encodeURIComponent).join("/")))
      .split("\n")
      .slice(0, 14)
      .join("\n");
    const match = head.match(/^# ([A-Z]{3}\d\d-J)\.? ?(.*)$/m);
    if (!match || !ALLOWED.has(match[1])) continue;
    const parts = file.split("/");
    rules.push({
      id: match[1],
      title: match[2]
        .trim()
        .replace(/\.$/, "")
        .replace(/\\([[\]])/g, "$1"),
      path: `${parts[parts.length - 2].replace(/^\d+\./, "")}/${parts[parts.length - 1].replace(/^\d+\./, "").replace(/\.md$/, "")}`,
    });
  }
}
await Promise.all(Array.from({ length: 8 }, worker));
rules.sort((a, b) => a.id.localeCompare(b.id));

const cwes = {};
for (const line of (await get(RAW + CWE_PAGE)).split("\n")) {
  const match = line.match(/^\| \[([A-Z]{3}\d\d-J)\]\([^)]*\) \| \[CWE-(\d+)/);
  if (match) (cwes[match[1]] ??= []).push(`CWE-${match[2]}`);
}

const q = JSON.stringify;
let out = `// Generated by scripts/generate-cert-java.mjs from the SEI CERT Oracle Coding Standard for Java
// source repository (commit ${COMMIT.slice(0, 7)}). Ids, titles and CWE ids only.
// See NOTICE.md for provenance and license.
import type { CertJavaRule } from "./types.js";

export const CERT_JAVA_RULES: readonly CertJavaRule[] = [
`;
for (const rule of rules) {
  const cwe = [...new Set(cwes[rule.id] ?? [])];
  out += `  { id: ${q(rule.id)}, title: ${q(rule.title)}, path: ${q(rule.path)}, cwe: [${cwe.map(q).join(", ")}] },\n`;
}
out += "];\n";
process.stdout.write(out);
