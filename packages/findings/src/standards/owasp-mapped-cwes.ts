const categoryByCwe = new Map<string, OwaspId>(
  (Object.entries(OWASP_MAPPED_CWES) as Array<[OwaspId, readonly string[]]>).flatMap(
    ([category, ids]) => ids.map((id): [string, OwaspId] => [id, category]),
  ),
);

/** The OWASP Top 10:2025 category whose mapped-CWE list contains this CWE, if any. */
export function owaspCategoryForCwe(cwe: string): OwaspId | undefined {
  return categoryByCwe.get(cwe);
}

