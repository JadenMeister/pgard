// Writes (or with --check, verifies) packages/scan-core/src/analyzer-hash.ts: a SHA-256 over the
// source of everything that decides what a scan reports for one file or one commit range. An
// incremental scan reuses stored per-file results only when this hash is unchanged, so editing an
// analyzer, a finding factory, the redaction or the fingerprint makes the next scan a full one.
// The hash lives in a source file so it is also inside the single-package bundle.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = "packages/scan-core/src/analyzer-hash.ts";
/** Directories whose non-test source shapes findings. */
const INPUTS = [
  "packages/source-analysis/src",
  "packages/git-history/src",
  "packages/findings/src",
  "packages/scan-core/src",
];

function isTestFile(relative) {
  return (
    /\.test\.tsx?$/.test(relative) ||
    relative.includes("/test-support/") ||
    relative.endsWith("/test-support.ts") ||
    relative.includes("/fixtures/") ||
    relative.endsWith("/analyzer-hash.ts")
  );
}

function listFiles(directory) {
  return readdirSync(path.join(root, directory), { withFileTypes: true }).flatMap((entry) => {
    const relative = `${directory}/${entry.name}`;
    if (entry.isDirectory()) return listFiles(relative);
    return /\.tsx?$/.test(entry.name) && !isTestFile(relative) ? [relative] : [];
  });
}

export function computeAnalyzerHash() {
  const hash = createHash("sha256");
  for (const relative of INPUTS.flatMap(listFiles).sort()) {
    // Line endings differ between checkouts; the logic does not.
    const text = readFileSync(path.join(root, relative), "utf8").replace(/\r\n/g, "\n");
    hash.update(`${relative}\n${text.length}\n${text}\n`);
  }
  return hash.digest("hex");
}

const header =
  "// Generated by scripts/analyzer-hash.mjs (run by `npm run build`); do not edit by hand.\n";
const expected = `${header}export const ANALYZER_HASH = "${computeAnalyzerHash()}";\n`;
const target = path.join(root, OUTPUT);
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing
  }
  if (current !== expected) {
    console.error(`${OUTPUT} is out of date: run \`node scripts/analyzer-hash.mjs\`.`);
    process.exit(1);
  }
} else {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing
  }
  if (current !== expected) writeFileSync(target, expected);
}
